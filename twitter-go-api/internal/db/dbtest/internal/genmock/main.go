// Command genmock writes dbtest.MockStore from the sqlc-generated db.Querier
// interface, so the fake never drifts from the queries. Run via `go generate`.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"strings"
)

func main() {
	if len(os.Args) != 3 {
		log.Fatal("usage: genmock <path/to/querier.go> <output.go>")
	}
	src, out := os.Args[1], os.Args[2]

	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, src, nil, 0)
	if err != nil {
		log.Fatal(err)
	}

	var methods []*ast.Field
	ast.Inspect(file, func(n ast.Node) bool {
		ts, ok := n.(*ast.TypeSpec)
		if !ok || ts.Name.Name != "Querier" {
			return true
		}
		methods = ts.Type.(*ast.InterfaceType).Methods.List
		return false
	})
	if len(methods) == 0 {
		log.Fatal("Querier interface not found")
	}

	var fields, impls bytes.Buffer
	for _, m := range methods {
		name := m.Names[0].Name
		fn := m.Type.(*ast.FuncType)
		params, args := signatureParams(fn)
		results, zeros := signatureResults(fn)

		fmt.Fprintf(&fields, "\t%sFn func(%s) %s\n", name, params, results)
		fmt.Fprintf(&impls, "\nfunc (m *MockStore) %s(%s) %s {\n\tif m.%sFn == nil {\n\t\treturn %s\n\t}\n\treturn m.%sFn(%s)\n}\n",
			name, params, results, name, zeros, name, args)
	}

	code := fmt.Sprintf(template, fields.String(), impls.String())
	if strings.Contains(code, "pgconn.") { // :execresult queries return pgconn.CommandTag
		code = strings.Replace(code, `"context"`, "\"context\"\n\n\t\"github.com/jackc/pgx/v5/pgconn\"", 1)
	}
	formatted, err := format.Source([]byte(code))
	if err != nil {
		log.Fatalf("format generated code: %v\n%s", err, code)
	}
	if err := os.WriteFile(out, formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}

func signatureParams(fn *ast.FuncType) (string, string) {
	var params, args []string
	for i, p := range fn.Params.List {
		name := fmt.Sprintf("p%d", i)
		params = append(params, name+" "+qualify(p.Type))
		args = append(args, name)
	}
	return strings.Join(params, ", "), strings.Join(args, ", ")
}

func signatureResults(fn *ast.FuncType) (string, string) {
	var types, zeros []string
	for _, r := range fn.Results.List {
		t := qualify(r.Type)
		types = append(types, t)
		if t == "error" {
			zeros = append(zeros, "nil")
		} else {
			zeros = append(zeros, "*new("+t+")")
		}
	}
	if len(types) == 1 {
		return types[0], zeros[0]
	}
	return "(" + strings.Join(types, ", ") + ")", strings.Join(zeros, ", ")
}

// qualify prints a type expression, prefixing db-package types with "db.".
func qualify(expr ast.Expr) string {
	switch e := expr.(type) {
	case *ast.Ident:
		if ast.IsExported(e.Name) {
			return "db." + e.Name
		}
		return e.Name
	case *ast.SelectorExpr:
		return qualify(e.X) + "." + e.Sel.Name
	case *ast.StarExpr:
		return "*" + qualify(e.X)
	case *ast.ArrayType:
		return "[]" + qualify(e.Elt)
	default:
		log.Fatalf("unsupported type expression %T", expr)
		return ""
	}
}

const template = `// Code generated by genmock from db.Querier; DO NOT EDIT.

package dbtest

import (
	"context"

	"github.com/chanombude/twitter-go-api/internal/db"
)

var _ db.Store = (*MockStore)(nil)

// MockStore is a db.Store whose queries call the matching XxxFn hook, or return
// zero values when the hook is nil. Transactions run inline on the same mock.
type MockStore struct {
%s}

func (m *MockStore) ExecTx(_ context.Context, fn func(db.Querier) error) error {
	return fn(m)
}

func (m *MockStore) ExecTxAfterCommit(_ context.Context, fn func(db.Querier) error, afterCommit func()) error {
	if err := fn(m); err != nil {
		return err
	}
	if afterCommit != nil {
		afterCommit()
	}
	return nil
}

func (m *MockStore) Ping(context.Context) error { return nil }
%s`
