#!/usr/bin/env python3
"""
Generates rules/slo.yml: error-ratio recording rules for each SLO over every window, plus
multi-window, multi-burn-rate alerts (Google SRE Workbook, "Alerting on SLOs").
Edit the SLOS table, then run:  python3 infra/observability/prometheus/gen_slo_rules.py
(CI fails if rules/slo.yml is out of date.)
"""
from pathlib import Path

# Probes and scrapes aren't people's requests
REQUESTS = 'path!~"/metrics|/healthz|/readyz"'
# ...and event streams stay open for minutes, so they'd count as slow by design
TIMED = 'path!~"/metrics|/healthz|/readyz|/api/v1/events|/api/v1/assistant"'

SLOS = [
    {
        "name": "api_availability",
        "title": "API availability",
        "objective": 0.995,
        "desc": "99.5% of API requests don't fail with a 5xx",
        # `or vector(0)`: with no 5xx series at all, sum() returns nothing instead of 0
        "bad": f'(sum(rate(http_requests_total{{{REQUESTS},status=~"5.."}}[{{w}}])) or vector(0))',
        "total": f"sum(rate(http_requests_total{{{REQUESTS}}}[{{w}}]))",
    },
    {
        "name": "api_latency",
        "title": "API latency",
        "objective": 0.99,
        "desc": "99% of API requests finish within 500 ms",
        # 0.5 is one of the histogram's buckets (prometheus.DefBuckets in the API)
        "bad": f'(sum(rate(http_request_duration_seconds_count{{{TIMED}}}[{{w}}])) - sum(rate(http_request_duration_seconds_bucket{{{TIMED},le="0.5"}}[{{w}}])))',
        "total": f"sum(rate(http_request_duration_seconds_count{{{TIMED}}}[{{w}}]))",
    },
]
WINDOWS = ["5m", "30m", "1h", "2h", "6h", "1d", "3d"]
# (severity, burn rate, long window, short window): page within minutes, ticket within hours
BURNS = [("page", 14.4, "1h", "5m"), ("page", 6, "6h", "30m"), ("ticket", 3, "1d", "2h"), ("ticket", 1, "3d", "6h")]


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


out = ["# GENERATED by gen_slo_rules.py - edit that file, not this one.", "groups:"]
for slo in SLOS:
    n, budget = slo["name"], round(1 - slo["objective"], 6)
    out += [f"  - name: slo-{n}", "    rules:"]
    for w in WINDOWS:
        bad, total = slo["bad"].replace("{w}", w), slo["total"].replace("{w}", w)
        out += [f"      - record: slo:{n}:error_ratio_rate{w}", f"        expr: {q(f'{bad} / {total}')}"]
    for severity in ("page", "ticket"):
        expr = " or ".join(
            f"(slo:{n}:error_ratio_rate{long} > ({rate} * {budget}) and slo:{n}:error_ratio_rate{short} > ({rate} * {budget}))"
            for sev, rate, long, short in BURNS
            if sev == severity
        )
        fast = severity == "page"
        out += [
            f"      - alert: {''.join(p.title() for p in n.split('_'))}{'Fast' if fast else 'Slow'}Burn",
            f"        expr: {q(expr)}",
            "        labels:",
            f"          severity: {severity}",
            f"          slo: {n}",
            "        annotations:",
            f"          summary: {q(slo['title'] + ' SLO is burning its error budget ' + ('fast' if fast else 'slowly'))}",
            f"          description: {q('SLO: ' + slo['desc'] + '. Current error ratio: {{ $value | humanizePercentage }}.')}",
            f"          runbook_url: {q('infra/observability/README.md#' + n.replace('_', '-'))}",
        ]

Path(__file__).with_name("rules").joinpath("slo.yml").write_text("\n".join(out) + "\n")
print("wrote rules/slo.yml")
